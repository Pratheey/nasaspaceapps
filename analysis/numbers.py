"""H-14 for the analysis lane: every number the app or pitch shows that comes from our files.

Reads the files the app actually loads (frontend/public/data/), recomputes each number the same way
the app does, and writes analysis/NUMBERS.md with value + source (file, field, how). Rerun after the
data freeze (hour 34) and before the video, then hand the table to Ryan for docs/pitch/numbers.md.

    python -m analysis.numbers
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
DATA = REPO / "frontend" / "public" / "data"
DEMO_EXTRA = ("P294", "P298")          # calm alternatives to P300
WINTER_END = "2026-03-31"              # "winter rise" = highest point up to this date, from the first date


def load():
    rd = lambda n: json.loads((DATA / f"{n}.json").read_text(encoding="utf-8"))
    return rd("meta"), rd("grid"), rd("series"), rd("stations")


def arr(v, scale=1.0):
    return np.array([np.nan if x is None else x for x in v], dtype=float) * scale


def cm(x, nd=1):
    return "–" if x is None or not np.isfinite(x) else f"{x:+.{nd}f}"


def winter_rise(dates, series, k0):
    """Highest position from date index k0 up to WINTER_END, relative to date k0 (cm)."""
    s = arr(series, 100)
    ok = np.isfinite(s)
    if k0 is None or not ok[k0]:
        return np.nan, None
    win = [k for k in range(k0, len(dates)) if dates[k] <= WINTER_END and ok[k]]
    if not win:
        return np.nan, None
    k = max(win, key=lambda k: s[k])
    return float(s[k] - s[k0]), dates[k]


def build() -> str:
    meta, grid, series, stations = load()
    dates, n = meta["dates"], meta["grid"]["nrows"] * meta["grid"]["ncols"]
    label = np.array(grid["label"]); net = arr(grid["net_change_m"], 100)
    sig = meta["sigma_net_m"] * 100
    measured = np.isfinite(net)
    g = meta["grid"]; km2 = (g["step_deg"] * 111) * (g["step_deg"] * 111 * math.cos(math.radians(36.45)))
    sinking = measured & np.isin(label, (1, 3))
    worst = int(np.nanargmin(net)); wr, wc = divmod(worst, g["ncols"])
    wlat = g["lat_max"] - (wr + 0.5) * g["step_deg"]; wlon = g["lon_min"] + (wc + 0.5) * g["step_deg"]
    counts = np.bincount(label, minlength=4)

    L = ["# NUMBERS.md: analysis-lane numbers shown in the app or pitch (H-14)", "",
         f"Generated by `python -m analysis.numbers` from `frontend/public/data/` (created {meta['created_utc']}, "
         f"is_synthetic = {str(meta['is_synthetic']).lower()}). Rerun when the app data changes.",
         "Every value is recomputed the way the app computes it. Ryan copies the rows into `docs/pitch/numbers.md`.", "",
         "## App: overview and \"By the numbers\"", "",
         "| Number as shown | Value | Source | How |", "|---|---|---|---|",
         f"| Radar passes (numbers.md #4) | {len(dates)} ({dates[0]} to {dates[-1]}) | `meta.json` → `dates` | count |",
         f"| Area measured | {round(measured.sum() * km2):,} km² | `grid.json` → `net_change_m` | cells with a net change × cell area at 36.45° N (as `story/Game.jsx`) |",
         f"| Share sinking beyond the uncertainty | {100 * sinking.sum() / measured.sum():.0f}% | `grid.json` → `label`, `net_change_m` | labels 1 or 3 ÷ cells with a net change (as `Game.jsx`) |",
         f"| Most any spot moved | {net[worst]:.1f} ± {sig:.1f} cm at {wlat:.3f} N, {-wlon:.3f} W | `grid.json` → `net_change_m` | single most-negative cell; one cell, so quote with its ± |",
         *[f"| Overview share: {meta['labels'][str(k)]} | {round(100 * counts[k] / n)}% ({counts[k]:,} cells) | `grid.json` → `label` | count ÷ all {n:,} cells, rounded (as `Inspector.jsx`) |" for k in (1, 3, 2, 0)],
         f"| Cells with a net change | {measured.sum():,} of {n:,} ({100 * measured.mean():.0f}%) | `grid.json` → `net_change_m` | non-null |",
         f"| σ of net change (± on every net change) | {sig:.2f} cm | `meta.json` → `sigma_net_m` ← `gps/processed/uncertainty.json` | Daniel's held-out GPS residuals |",
         f"| Seasonal test | {meta['significance']} | `meta.json` → `significance` | calibrated on the stable control boxes |",
         *[f"| Trend guard | {nt[len('Trend guard: '):]} | `meta.json` → `notes` | `analysis/guards.py` |" for nt in meta["notes"] if nt.startswith("Trend guard:")],
         "", "**Wording:** measured cells include the hills; say \"of ground measured\".", ""]

    L += ["## Demo stations (numbers.md #7)", "",
          f"NISAR = the station's 1 km cell (`stations.json` → `nisar`, `nisar_fit`); GPS = `stations.json` → `gps`, `gps_fit`; "
          f"residual = the difference of the two displayed net changes, not `residuals.net_m` (the separate native-pixel validation). NISAR and GPS net change and winter rise are both measured from the "
          f"**common start** (first date where both have a value; GPS at CAFP, CAHA, CAFR, CAKC, TRAN starts 2025-12-06); "
          f"winter rise = highest point up to {WINTER_END}. ± on NISAR net change is σ = {sig:.2f} cm.", "",
          "| Station | Role | Common start | NISAR net (cm) | GPS net (cm) | NISAR − GPS net (cm) | NISAR winter rise (cm, date) | GPS winter rise (cm, date) | NISAR trend (cm/yr) | GPS trend (cm/yr) | NISAR seasonal A (mm), peak month | GPS seasonal A (mm), peak month | NISAR dates |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    by = {s["station"]: s for s in stations["stations"]}
    demo = meta.get("demo_stations", {})
    order = list(demo.get("sinking", [])) + [demo.get("calm")] + [s for s in DEMO_EXTRA if s in by]
    for name in dict.fromkeys(s for s in order if s in by):
        s = by[name]; ns = arr(s["nisar"]["los_m"], 100); gs = arr(s["gps"]["los_m"], 100)
        role = "demo, sinking" if name in demo.get("sinking", []) else ("demo, calm" if name == demo.get("calm") else "calm alternative")
        both = np.flatnonzero(np.isfinite(ns) & np.isfinite(gs))
        k0 = int(both[0]) if len(both) else None
        def net_of(x):
            return x[-1] - x[k0] if k0 is not None and np.isfinite(x[-1]) and np.isfinite(x[k0]) else np.nan
        nf, gf = s["nisar_fit"], s["gps_fit"]
        nwr, nwd = winter_rise(dates, s["nisar"]["los_m"], k0); gwr, gwd = winter_rise(dates, s["gps"]["los_m"], k0)
        res = net_of(ns) - net_of(gs)
        amp_n = "not significant" if not nf.get("seasonal_significant") else f"{nf['amp_m'] * 1000:.1f} ± {nf['amp_sigma_m'] * 1000:.1f}"
        pm = None
        if nf.get("seasonal_significant") and nf.get("a_m") is not None:
            pm = int(((math.atan2(nf["a_m"], nf["b_m"]) / (2 * math.pi)) % 1.0) * 12) + 1
        amp_g = "–" if gf.get("amp_m") is None else f"{gf['amp_m'] * 1000:.1f} ± {gf['amp_sigma_m'] * 1000:.1f}, {gf.get('peak_month')}"
        tr = lambda f: "–" if f.get("trend_m_per_yr") is None else f"{f['trend_m_per_yr'] * 100:+.1f} ± {f['trend_sigma_m_per_yr'] * 100:.1f}"
        start = "–" if k0 is None else dates[k0]
        L.append(f"| {name} | {role} | {start} | {cm(net_of(ns))} ± {sig:.1f} | {cm(net_of(gs))} | {cm(res)} | "
                 f"{cm(nwr)} ({nwd}) | {cm(gwr)} ({gwd}) | {tr(nf)} | {tr(gf)} | {amp_n}{'' if pm is None else f', {pm}'} | {amp_g} | "
                 f"{int(np.isfinite(ns).sum())} of {len(dates)} |")
    L += ["", "Trends rest on less than a year of data and are never the headline (PROPOSAL §5). NISAR and GPS trends here "
          "are each in absolute LOS (tied to P304), so they compare directly.", ""]

    # Pick Two Dates candidate from the pitch (docs/pitch/pitch.md)
    d1, d2, st = "2025-12-06", "2026-02-04", "CAHA"
    if st in by and d1 in dates and d2 in dates:
        k1, k2 = dates.index(d1), dates.index(d2); s = by[st]
        n1, n2 = s["nisar"]["los_m"][k1], s["nisar"]["los_m"][k2]; g1, g2 = s["gps"]["los_m"][k1], s["gps"]["los_m"][k2]
        ns, gs = arr(s["nisar"]["los_m"], 100), arr(s["gps"]["los_m"], 100)
        full_n = ns[-1] - ns[k1] if np.isfinite(ns[-1]) and np.isfinite(ns[k1]) else np.nan
        full_g = gs[-1] - gs[k1] if np.isfinite(gs[-1]) and np.isfinite(gs[k1]) else np.nan
        diff = lambda a, b: None if a is None or b is None else (b - a) * 100
        L += ["## Pick Two Dates candidate (pitch line 2)", "",
              "| | NISAR (cm) | GPS (cm) | Source |", "|---|---|---|---|",
              f"| {st}, {d1} → {d2} (the two dates that \"look fine\") | {cm(diff(n1, n2))} | {cm(diff(g1, g2))} | `stations.json` → `{st}.nisar.los_m`, `gps.los_m` at those dates |",
              f"| {st}, {d1} → {dates[-1]} (the full record from the same start) | {cm(full_n)} | {cm(full_g)} | same |", "",
              f"A single two-date difference has noise of about √2 × the per-date scatter; quote it with σ_pair ≈ 1.8 cm (D9).", ""]
    return "\n".join(L) + "\n"


def main() -> None:
    out = REPO / "analysis" / "NUMBERS.md"
    out.write_text(build(), encoding="utf-8")
    print("wrote", out.relative_to(REPO))


if __name__ == "__main__":
    main()
